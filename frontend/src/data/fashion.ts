export function fashionToProduct(p: FashionProduct): import("@/types").Product {
  return {
    id: p.id,
    slug: p.slug,
    title: p.title,
    category: p.category,
    categorySlug: p.categorySlug,
    price: p.price,
    oldPrice: p.oldPrice,
    rating: p.rating,
    image: p.image,
    flag: p.flag === "Trend" ? "New" : p.flag ?? null,
    stock: p.stock,
    unit: p.unit,
    description: p.title,
    sizes: p.sizes,
  };
}

