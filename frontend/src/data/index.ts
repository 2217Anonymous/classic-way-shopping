export function getProductBySlug(slug: string) {
  const grocery = products.find((p) => p.slug === slug);
  if (grocery) return grocery;
  const fashion = fashionProducts.find((p) => p.slug === slug);
  return fashion ? fashionToProduct(fashion) : undefined;
}

export function getAllProducts(): Product[] {
  return [...products, ...fashionProducts.map(fashionToProduct)];
}

export function getProductsByCategory(categorySlug: string) {
  return products.filter((p) => p.categorySlug === categorySlug);
}

export function getBlogBySlug(slug: string) {
  return blogs.find((b) => b.slug === slug);
}

export function getRelatedProducts(product: Product, limit = 4) {
  return products
    .filter((p) => p.id !== product.id && p.categorySlug === product.categorySlug)
    .slice(0, limit);
}
